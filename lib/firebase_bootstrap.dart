import 'package:firebase_app_check/firebase_app_check.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

import 'firebase_options.dart';

/// reCAPTCHA v3 site key for web builds, passed at compile time so real keys
/// never live in source control:
///
/// ```bash
/// flutter build web --dart-define=APPCHECK_WEB_SITE_KEY=your-site-key
/// ```
const _webRecaptchaSiteKey = String.fromEnvironment(
  'APPCHECK_WEB_SITE_KEY',
  defaultValue: '',
);

/// App Check debug token for release APKs installed outside Google Play.
///
/// Play Integrity only passes for apps installed from Google Play, so a
/// sideloaded release APK gets rejected by App Check and AI calls fail. For
/// APKs you hand out yourself, register a debug token in Firebase console >
/// App Check > Apps > (Android app) > Manage debug tokens, then build with:
///
/// ```bash
/// flutter build apk --dart-define=APPCHECK_ANDROID_DEBUG_TOKEN=your-token
/// ```
///
/// Every phone that installs an APK built this way passes App Check. The token
/// is embedded in the APK and can be extracted from it, so keep the Gemini
/// Developer API on the free tier (no billing) and set a per-user rate limit
/// in Firebase AI Logic. Revoke the token in the console to cut off old APKs,
/// and switch to Google Play distribution (Play Integrity) for a public launch.
const _androidDebugToken = String.fromEnvironment(
  'APPCHECK_ANDROID_DEBUG_TOKEN',
  defaultValue: '',
);

/// Initializes Firebase and App Check when credentials are available.
///
/// The credentials come from `lib/firebase_options.dart`, which is generated by
/// `flutterfire configure`. When that file is still the unconfigured
/// placeholder, or the current platform has no Firebase app registered,
/// initialization is skipped and the app runs against the in-memory demo store.
class FirebaseBootstrap {
  static bool _initialized = false;
  static bool _appCheckEnabled = false;

  /// Name of the second Firebase app used only for buyer chat.
  static const chatAppName = 'buyer-chat';
  static FirebaseApp? _chatApp;

  /// A separate Firebase app (same project) whose sign-in is the buyer's
  /// guest account. Keeping it apart from the default app means a shop owner
  /// signing in or out never replaces the buyer's guest account, so their
  /// chats stay in "My messages". Null when Firebase is not set up.
  static FirebaseApp? get chatApp => _chatApp;

  /// Whether a Firebase app was successfully initialized in this process.
  static bool get isInitialized => _initialized;

  /// Whether Firebase App Check is enforcing requests in this process.
  static bool get isAppCheckEnabled => _appCheckEnabled;

  static Future<void> initialize() async {
    if (Firebase.apps.isNotEmpty) {
      _initialized = true;
      await _initChatApp(Firebase.app().options);
      await _activateAppCheck();
      return;
    }

    final FirebaseOptions options;
    try {
      options = DefaultFirebaseOptions.currentPlatform;
    } on UnsupportedError catch (error) {
      debugPrint(
        'Firebase is not configured: ${error.message}. '
        'Run `flutterfire configure` to generate lib/firebase_options.dart. '
        'Using in-memory demo data.',
      );
      return;
    }

    try {
      await Firebase.initializeApp(options: options);
      _initialized = true;
      debugPrint('Firebase initialized for project ${options.projectId}.');
    } catch (error) {
      debugPrint(
        'Firebase initialization failed: $error. Using in-memory demo data.',
      );
      return;
    }

    await _initChatApp(options);
    await _activateAppCheck();
  }

  static Future<void> _initChatApp(FirebaseOptions options) async {
    try {
      _chatApp =
          Firebase.apps.where((app) => app.name == chatAppName).firstOrNull ??
          await Firebase.initializeApp(name: chatAppName, options: options);
    } catch (error) {
      // Chat then falls back to the default app's sign-in.
      debugPrint('Buyer chat app failed to start: $error');
    }
  }

  /// App Check for the default app and the buyer chat app.
  static List<FirebaseAppCheck> _appChecks() => [
    FirebaseAppCheck.instance,
    if (_chatApp case final chatApp?)
      FirebaseAppCheck.instanceFor(app: chatApp),
  ];

  /// Activates App Check without ever blocking app startup. Debug builds skip
  /// enforcement unless a site key or provider is explicitly configured.
  static Future<void> _activateAppCheck() async {
    try {
      if (kIsWeb) {
        if (_webRecaptchaSiteKey.isEmpty) {
          // Expected while developing; only warn when a release build ships
          // without App Check.
          if (kReleaseMode) {
            debugPrint(
              'SECURITY: App Check skipped: pass '
              '--dart-define=APPCHECK_WEB_SITE_KEY=... to enforce web builds.',
            );
          }
          return;
        }
        for (final appCheck in _appChecks()) {
          await appCheck.activate(
            providerWeb: ReCaptchaV3Provider(_webRecaptchaSiteKey),
          );
        }
      } else if (kDebugMode) {
        debugPrint(
          'App Check skipped in debug mode. Register a debug token in the '
          'Firebase console and activate it explicitly to test enforcement.',
        );
        return;
      } else {
        for (final appCheck in _appChecks()) {
          await appCheck.activate(
            providerAndroid: _androidDebugToken.isEmpty
                ? const AndroidPlayIntegrityProvider()
                : const AndroidDebugProvider(debugToken: _androidDebugToken),
            providerApple: const AppleAppAttestProvider(),
          );
        }
      }
      _appCheckEnabled = true;
      debugPrint('App Check activated.');
    } catch (error) {
      debugPrint('App Check activation failed: $error. Continuing without it.');
    }
  }
}
