import 'package:firebase_app_check/firebase_app_check.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

import 'firebase_options.dart';

/// reCAPTCHA v3 site key for web builds, passed at compile time so real keys
/// never live in source control:
///
/// ```bash
/// flutter build web --dart-define=APPCHECK_WEB_SITE_KEY=your-site-key
/// ```
const _webRecaptchaSiteKey = String.fromEnvironment(
  'APPCHECK_WEB_SITE_KEY',
  defaultValue: '',
);

/// Initializes Firebase and App Check when credentials are available.
///
/// The credentials come from `lib/firebase_options.dart`, which is generated by
/// `flutterfire configure`. When that file is still the unconfigured
/// placeholder, or the current platform has no Firebase app registered,
/// initialization is skipped and the app runs against the in-memory demo store.
class FirebaseBootstrap {
  static bool _initialized = false;
  static bool _appCheckEnabled = false;

  /// Whether a Firebase app was successfully initialized in this process.
  static bool get isInitialized => _initialized;

  /// Whether Firebase App Check is enforcing requests in this process.
  static bool get isAppCheckEnabled => _appCheckEnabled;

  static Future<void> initialize() async {
    if (Firebase.apps.isNotEmpty) {
      _initialized = true;
      await _activateAppCheck();
      return;
    }

    final FirebaseOptions options;
    try {
      options = DefaultFirebaseOptions.currentPlatform;
    } on UnsupportedError catch (error) {
      debugPrint(
        'Firebase is not configured: ${error.message}. '
        'Run `flutterfire configure` to generate lib/firebase_options.dart. '
        'Using in-memory demo data.',
      );
      return;
    }

    try {
      await Firebase.initializeApp(options: options);
      _initialized = true;
      debugPrint('Firebase initialized for project ${options.projectId}.');
    } catch (error) {
      debugPrint(
        'Firebase initialization failed: $error. Using in-memory demo data.',
      );
      return;
    }

    await _activateAppCheck();
  }

  /// Activates App Check without ever blocking app startup. Debug builds skip
  /// enforcement unless a site key or provider is explicitly configured.
  static Future<void> _activateAppCheck() async {
    try {
      if (kIsWeb) {
        if (_webRecaptchaSiteKey.isEmpty) {
          final message =
              'App Check skipped: pass --dart-define=APPCHECK_WEB_SITE_KEY=... '
              'to enforce web builds.';
          if (kReleaseMode) {
            debugPrint('SECURITY: $message');
          } else {
            debugPrint(message);
          }
          return;
        }
        await FirebaseAppCheck.instance.activate(
          providerWeb: ReCaptchaV3Provider(_webRecaptchaSiteKey),
        );
      } else if (kDebugMode) {
        debugPrint(
          'App Check skipped in debug mode. Register a debug token in the '
          'Firebase console and activate it explicitly to test enforcement.',
        );
        return;
      } else {
        await FirebaseAppCheck.instance.activate(
          providerAndroid: const AndroidPlayIntegrityProvider(),
          providerApple: const AppleAppAttestProvider(),
        );
      }
      _appCheckEnabled = true;
      debugPrint('App Check activated.');
    } catch (error) {
      debugPrint('App Check activation failed: $error. Continuing without it.');
    }
  }
}
